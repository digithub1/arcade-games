    getSdkLanguage() {
        const gp = this.getGp();
        if (!gp || typeof gp.language !== 'string' || !gp.language) {
            return null;
        }

        const code = String(gp.language).split('-')[0].toLowerCase();
        return code || null;
    },

    syncSdkLanguage(language) {
        const normalized = this.resolveSdkLanguage(language);
        this.commitResolvedLanguage(normalized);
        return this.refreshSdkDependentViews().then(() => true);
    },

