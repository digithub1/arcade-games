			bullet.dead = 0;
			bullet.powerHitArea = null;
			if (powerHit) {
				var power = new lib.PowerHitArea();
				bullet.powerHitArea = power;
				bullet.pc.addChildAt(power, 0);
				powerHit = false;
			}
			var angle = barrel.rotation / 180 * Math.PI;
			bullet.rotation = barrel.rotation
			bullet.vx = speed * Math.cos(angle);
			bullet.vy = speed * Math.sin(angle);
			bullet.x = barrel.x + 120 * Math.cos(angle);
			bullet.y = barrel.y + 120 * Math.sin(angle);
			bullet.startX = bullet.x;
			bullet.startY = bullet.y;
			bullets_arr.push(bullet);
			lg.playSFX("ShootSound");
			shapeGFX = line_shape.graphics;
			gameplay.addChild(line_shape);
			line_shape.alpha = 0.5;
			gameplay.addChild(bullet);
