		function getSudokuBoard() {
			var keys = [1, 2, 3, 4, 5, 6];
			var itms = [];
			while (keys.length > 0) {
				var idx = Math.floor(keys.length * Math.random());
				itms.push(keys[idx]);
				keys.splice(idx, 1);
			}
		
		
			var startNum = [0, 3, 1, 4, 2, 5];
			var sudArr = "";
			for (var i = 0; i < 3; i++) {
				for (var j = 0; j < 2; j++) {
					var startIDX = getIDX();
					for (var k = 0; k < 6; k++) {
						sudArr += itms[startIDX];
						startIDX++;
						if (startIDX == itms.length) {
							startIDX = 0;
						}
					}
					sudArr += "*";
				}
			}
			function getIDX() {
				var idx = startNum[0];
				startNum.splice(0, 1);
				return idx;
			}
			sudArr = sudArr.substr(0, sudArr.length - 1);
			return sudArr;
		}
		
