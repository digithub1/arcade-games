		function getSudokuBoard() {
			var keys = [1, 2, 3, 4];
			var itms = [];
			while (keys.length > 0) {
				var idx = Math.floor(keys.length * Math.random());
				itms.push(keys[idx]);
				keys.splice(idx, 1);
			}
		
		
			var startNum = [0, 2, 1, 3];
			var sudArr = "";
		
			for (var i = 0; i < 4; i++) {
				var startIDX = getIDX();
				for (var j = 0; j < 4; j++) {
					sudArr += itms[startIDX];
					startIDX++;
					if (startIDX == itms.length) {
						startIDX = 0;
					}
				}
				sudArr += "*";
			}
			function getIDX() {
				var idx = startNum[0];
				startNum.splice(0, 1);
				return idx;
			}
			sudArr = sudArr.substr(0, sudArr.length - 1);
			console.log("XLSLSDF:", sudArr);
			return sudArr;
		}
		
		function boardToGrid(str) {
			var arr = str.split('*');
			for (var i = 0; i < arr.length; i++) {
				arr[i] = arr[i].split('');
			}
			return arr;
		}
		
		function makePuzzle(gridSol) {
			var blankPos = [];
			if (gv.mode != "easy") {
				blankPos = [
					[0, 2],
					[0, 1],
					[1, 3],
					[0, 2],
					[1, 2]
				];
			} else {
				blankPos = [
					[0],
					[1],
					[2],
					[0, 2],
					[1, 2]
				];
			}
		
			randomizeArray(blankPos);
			for (var i = 0; i < 4; i++) {
				var br = blankPos[i];
				for (var j = 0; j < 4; j++) {
					if (br.indexOf(j) >= 0) {
						gridSol[i][j] = ".";
					}
				}
		
			}
			return gridSol;
		}
		
		
		
		function checkGroupGrid(gridArr) {
			for (var arr of gridArr) {
				var narr = [];
				for (var cf of arr) {
					if (narr.indexOf(cf) < 0) {
						narr.push(cf);
					}
				}
		
				if (narr.length < 4) {
					return false;
				}
			}
			return true;
		}
		
		
		function checkRowCols(grid) {
			for (var i = 0; i < 4; i++) {
				var tot1 = 0;
				var tot2 = 0;
				for (var j = 0; j < 4; j++) {
					tot1 += Number(grid[i][j]);
					tot2 += Number(grid[j][i]);
				}
				if (tot1 != 10 || tot2 != 10) {
					return false;
				}
			}
			return true;
		}
		
		function getDupArray(arr) {
			var dupArr = [
				[],
				[],
				[],
				[]
		
			];
			for (var i = 0; i < 4; i++) {
				for (var j = 0; j < 4; j++) {
					dupArr[i][j] = arr[i][j];
				}
			}
			return dupArr;
		}
